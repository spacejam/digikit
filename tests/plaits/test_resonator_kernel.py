"""RINGS' resonator kernels (modules/machines/plaits/src/dsp/lib/resonator_svf4_sm.s, the shipping one, and
resonator_svf4.s, both generated by gen_resonator_svf4.py)
on the isolated concrete SHARC+ core: resonator_svf4_band_pass_add with the kernel (the DSP build) against the same
function built with -DPL_SVF4_C (selcc's C loop, the code the core digests were recorded from), bit for bit on out[]
and the filter states, over random states, coefficients and inputs (denormals, +-0, large values, Inf and NaN) and every
even size the kernel takes, with guard words around every buffer; and the kernel leaves every register outside the
documented scratch set (R0-R8, R12, I4, I12 and the flags) as it found it, with SISD mode and an empty loop stack."""

from __future__ import annotations

import random
import struct
from functools import cache

import pytest

from tools.patchkit import pk_sharc, pk_toolchains

ROOT = pk_toolchains.ROOT
LIB = ROOT / "modules" / "machines" / "plaits" / "src" / "dsp" / "lib"
pytestmark = pytest.mark.skipif(
    pk_toolchains.selache_dir() is None,
    reason="selache not built (tools/patchkit/pk_toolchains.py selache)",
)

BASE_SW = 0xB92000
RETURN_SW = 0xBAF100
DATA = 0x200A0000
STACK = 0x200F0000  # as after CJUMP: I6 = STACK, [STACK] = the caller's I6, [STACK - 4] = return address - 1, I7 two below
CALLER_I6 = 0x200F0100
# test buffers (byte addresses in L2), each with guard words around it
S, F, Q, G, IN, OUT = (0x200B0000 + 0x400 * i for i in range(6))
GUARD = 0x5A5A5A5A
# the documented scratch set of resonator_svf4.s (selcc's caller-saved registers, LCNTR) and what the core changes as
# it runs (program counter, its stack registers, cycle and timer counters)
SCRATCH = {f"R{i}" for i in (0, 1, 2, 3, 4, 5, 6, 7, 8, 12)} | {
    "I4",
    "I12",
    "LCNTR",
    "CURLCNTR",
    "LADDR",
}
RUNNING = {
    "PC",
    "PCSTK",
    "PCSTKP",
    "EMUCLK",
    "EMUCLK2",
    "TCOUNT",
    "FADDR",
    "DADDR",
    "MODE1STK",
}
# the hook point's registers as the stock 1.17 renderer leaves them (boot set-up at sw 0x1c0f40..0x1c0fa2: M6 = 1,
# L0-L5, L8-L15 = 0, MODE1 = 0x1011800 (RND32, IRPTEN, CBUFEN, ...), MODE2 bit 0; the PLAITS shim zeroes L6/L7 for the C
# call) and selcc's constant modifiers
HOOK = {
    "M5": 0,
    "M6": 1,
    "M7": 0xFFFFFFFF,
    "M13": 0,
    "M14": 1,
    "M15": 0xFFFFFFFF,
    "MODE1": 0x1011800,
    "MODE2": 1,
    "L6": 0,
    "L7": 0,
}
FLAGS = {"ASTATX", "ASTATY", "STKYX", "STKYY"}


def bits(x: float) -> int:
    return struct.unpack("<I", struct.pack("<f", x))[0]


@cache
def built(
    kernel: str | None,
) -> tuple[pk_sharc.Linked, dict[str, int], list[tuple[int, bytes]]]:
    c = pk_sharc.compile_c(
        (LIB / "resonator.c").read_text(),
        include_dirs=[LIB],
        defines=() if kernel else ("PL_SVF4_C",),
    )
    objs = [pk_sharc.assemble((LIB / kernel).read_text()), c] if kernel else [c]
    obj = pk_sharc.merge(objs)
    at, blobs, externs = DATA, [], {}
    data_at = {}
    for sec, (blob, align, bss) in obj.data.items():
        at = -(-at // max(align, 8)) * max(align, 8)
        data_at[sec] = at
        blobs.append((at, bytes(len(blob)) if bss else blob))
        at += len(blob)
    for name, (sec, off, _g) in obj.data_symbols.items():
        externs[name] = data_at[sec] + off
    for rel in obj.relocs:
        if rel.symbol not in obj.symbols and rel.symbol not in externs:
            externs[rel.symbol] = (
                0x200E0000  # tables resonator_process reads; not called here
            )
    linked = pk_sharc.link(obj, BASE_SW, externs)
    pk_sharc.verify(obj, linked, externs)
    return linked, externs, blobs


class Core:
    def __init__(self, kernel: str | None) -> None:
        from tools.sharc_dev import sharc_run as sr
        from tools.sharc_dev import sharc_trace as st
        from tools.sharc_dev.sharcldr import LoadedMemory

        self.st = st
        self.linked, _ext, blobs = built(kernel)
        payload = self.linked.code_boot
        blocks = [
            {
                "target_address": pk_sharc.SW_ALIAS_BASE + 2 * BASE_SW,
                "byte_count": len(payload),
                "fill": False,
                "payload_offset": 0,
                "payload_len": len(payload),
                "index": 0,
            }
        ]
        for at, blob in blobs:
            blocks.append(
                {
                    "target_address": at,
                    "byte_count": len(blob),
                    "fill": False,
                    "payload_offset": len(payload),
                    "payload_len": len(blob),
                    "index": len(blocks),
                }
            )
            payload += blob
        self.mem = LoadedMemory(payload, blocks)
        self.runner = sr.Runner(
            self.mem, BASE_SW, breakpoints=[RETURN_SW], approx_recips=True
        )
        self.instructions = 0

    def poke(self, addr: int, word: int) -> None:
        assert self.st._dm_write(
            self.runner.state, addr, 4, self.st.Const(word & 0xFFFFFFFF)
        )

    def peek(self, addr: int) -> int:
        v = self.st._dm_read(self.runner.state, addr, 4)
        assert v is not None
        return int(v.value) & 0xFFFFFFFF

    def put(self, addr: int, words: list[int], guard: int = 2) -> None:
        for k in range(-guard, len(words) + guard):
            self.poke(addr + 4 * k, words[k] if 0 <= k < len(words) else GUARD)

    def get(self, addr: int, n: int, guard: int = 2) -> list[int]:
        return [self.peek(addr + 4 * k) for k in range(-guard, n + guard)]

    def call(
        self, name: str, args: list[int], regs: dict[str, int] | None = None
    ) -> dict[str, int | None]:
        """Call `name` (selcc's convention: R4, R8, R12, then the stack); return every register after it."""
        self.poke(STACK, CALLER_I6)
        self.poke(STACK - 4, RETURN_SW - 1)
        r: dict[str | int, int | str] = {
            "I6": STACK,
            "I7": STACK - 8,
            "M5": 0,
            "M6": 1,
            "M7": -1,
            "M13": 0,
            "M14": 1,
            "M15": -1,
        }
        r.update(regs or {})
        for reg, a in zip(("R4", "R8", "R12"), args[:3], strict=False):
            r[reg] = a & 0xFFFFFFFF
        for k, a in enumerate(args[3:]):
            self.poke(STACK + 4 * (k + 1), a)
        run = self.runner.fresh_call(
            self.linked.symbols[name], regs=r, return_address=RETURN_SW
        )
        st = run.state
        self.before = {n: self._val(st, c) for n, c in self.st.UREG_CODES.items()}
        self.depth_before = (len(st.loops), len(st.status_stack), len(st.call_stack))
        res = run.run(500_000)
        assert res.halt.reason == "breakpoint" and res.final_pc_sw == RETURN_SW, (
            res.halt.to_json()
        )
        assert not run.state.loops, "loop stack not empty on return"
        self.runner = run
        st = run.state
        self.depth_after = (len(st.loops), len(st.status_stack), len(st.call_stack))
        self.instructions = res.instructions
        return self.regs()

    @staticmethod
    def _val(state: object, code: int) -> int | None:
        v = state.uregs.get(code)  # type: ignore[attr-defined]
        x = None if v is None else getattr(v, "value", None)
        return None if x is None else int(x) & 0xFFFFFFFF

    def regs(self) -> dict[str, int | None]:
        out: dict[str, int | None] = {}
        for name, code in self.st.UREG_CODES.items():
            v = self.runner.state.uregs.get(code)
            out[name] = None if v is None else getattr(v, "value", None)
        return out


SPECIAL = [
    0.0,
    -0.0,
    1e-39,
    -1e-39,
    1e-45,
    3e38,
    -3e38,
    float("inf"),
    float("-inf"),
    float("nan"),
]


def rnd_float(rng: random.Random, special: float) -> int:
    if rng.random() < special:
        return bits(rng.choice(SPECIAL))
    return bits(rng.choice([1, -1]) * 10 ** rng.uniform(-6, 1))


def case(rng: random.Random, size: int, special: float) -> dict[str, list[int]]:
    f = [bits(rng.uniform(1e-4, 0.499)) for _ in range(4)]
    q = [bits(1.0 + rng.uniform(0, 1) * 10 ** rng.uniform(0, 3.5)) for _ in range(4)]
    g = [bits(rng.uniform(-0.25, 0.25)) for _ in range(4)]
    return {
        "s": [rnd_float(rng, special) for _ in range(8)],
        "f": f,
        "q": q,
        "g": g,
        "in": [rnd_float(rng, special) for _ in range(size)],
        "out": [rnd_float(rng, special) for _ in range(size)],
    }


def fn(core: Core) -> str:
    return (
        "resonator_svf4_kernel."
        if "resonator_svf4_kernel." in core.linked.symbols
        else "resonator_svf4_band_pass_add."
    )


def render(core: Core, c: dict[str, list[int]], size: int) -> tuple[list[int], ...]:
    for addr, key in ((S, "s"), (F, "f"), (Q, "q"), (G, "g"), (IN, "in"), (OUT, "out")):
        core.put(addr, c[key])
    core.call(fn(core), [S, F, Q, G, IN, OUT, size])
    return (
        core.get(OUT, size),
        core.get(S, 8),
        core.get(IN, size),
        core.get(F, 4),
        core.get(Q, 4),
        core.get(G, 4),
    )


# resonator_svf4_sm.s ships (no data transfer in SIMD mode); resonator_svf4.s (SIMD transfers, hung H-opt1) stays
# tested so its schedule remains a correct base for a later image once SIMD transfers are proven on the unit
@pytest.fixture(scope="module", params=["resonator_svf4_sm.s", "resonator_svf4.s"])
def cores(request: pytest.FixtureRequest) -> tuple[Core, Core]:
    return Core(request.param), Core(None)


@pytest.mark.parametrize("size", [16, 4, 6, 8, 10, 12, 14])
def test_kernel_equals_compiled_c(cores: tuple[Core, Core], size: int) -> None:
    ker, ref = cores
    rng = random.Random(1000 + size)
    for i in range(12 if size == 16 else 4):
        special = 0.0 if i % 3 == 0 else (0.05 if i % 3 == 1 else 0.4)
        c = case(rng, size, special)
        got, want = render(ker, c, size), render(ref, c, size)
        assert got == want, (size, i)


def test_kernel_runs_on_from_block_to_block(cores: tuple[Core, Core]) -> None:
    """A strike, then 40 blocks of 16 with small new input, carrying the states (the shape RINGS calls it with), bit for bit."""
    ker, ref = cores
    rng = random.Random(7)
    c = case(rng, 16, 0.0)
    c["s"] = [0] * 8
    c["in"] = [bits(0.3)] + [0] * 15
    states = {}
    for core in (ker, ref):
        for addr, key in ((S, "s"), (F, "f"), (Q, "q"), (G, "g")):
            core.put(addr, c[key])
    for blk in range(40):
        outs = []
        blk_in = (
            c["in"] if blk == 0 else [bits(rng.uniform(-1e-3, 1e-3)) for _ in range(16)]
        )
        for core in (ker, ref):
            core.put(IN, blk_in)
            core.put(OUT, [0] * 16)
            core.call(fn(core), [S, F, Q, G, IN, OUT, 16])
            outs.append((core.get(OUT, 16), core.get(S, 8)))
        assert outs[0] == outs[1], blk
        states[blk] = outs[0][1]
    assert states[39] != [0] * 12


def test_kernel_cost(cores: tuple[Core, Core]) -> None:
    """The kernel path of one call (16 samples) against the C loop: the instruction count the CPU figures rest on."""
    ker, ref = cores
    c = case(random.Random(3), 16, 0.0)
    render(ker, c, 16)
    render(ref, c, 16)
    assert ker.instructions < ref.instructions / 5, (ker.instructions, ref.instructions)


@pytest.mark.parametrize("seed", [11, 12])
def test_kernel_preserves_the_dsp_state(cores: tuple[Core, Core], seed: int) -> None:
    """resonator_svf4_kernel from the hook point's registers plus random values everywhere else (non-zero L and B on
    every DAG but the C stack's, the kernel's own L0/L1/L4 included, M6 != 1 on the second seed): every register outside
    the scratch set, every MODE1/MODE2 bit and the loop, status and PC stack depths are as before the call."""
    ker, _ = cores
    rng = random.Random(seed)
    size = 16
    c = case(rng, size, 0.0)
    for addr, key in ((S, "s"), (F, "f"), (Q, "q"), (G, "g"), (IN, "in"), (OUT, "out")):
        ker.put(addr, c[key])
    regs: dict[str, int] = dict(HOOK)
    for p in range(16):
        regs[f"R{p}"] = rng.getrandbits(32)
        regs[f"S{p}"] = rng.getrandbits(32)
    for i in (0, 1, 2, 3, 5, 8, 9, 10, 11, 13, 14, 15):
        regs[f"I{i}"] = 0x200C0000 + 4 * rng.randrange(1000)
        regs[f"B{i}"] = 0x200C0000 + 4 * rng.randrange(1000)
        regs[f"L{i}"] = 4 * rng.randrange(1, 64)
    # circular buffers over the very buffers the kernel walks: without its own L0 = L1 = L4 = 0 they would wrap
    regs["B0"], regs["L0"] = IN, 8
    regs["B4"], regs["L4"] = OUT, 8
    regs["B2"], regs["L2"] = OUT, 8
    for m in (0, 1, 2, 3, 4, 8, 9, 10, 11, 12):
        regs[f"M{m}"] = rng.randrange(-64, 64) & 0xFFFFFFFF
    if seed % 2 == 0:
        regs["M6"] = 3
    for u in ("USTAT1", "USTAT2", "USTAT3", "USTAT4", "PX1", "PX2", "LCNTR"):
        regs[u] = rng.getrandbits(32) if u != "LCNTR" else 5
    after = ker.call("resonator_svf4_kernel.", [S, F, Q, G, IN, OUT, size], regs)
    before = dict(ker.before)
    # RFRAME hands the caller's frame back: I6 = [STACK], I7 = STACK as before its CJUMP
    before["I6"], before["I7"] = CALLER_I6, STACK
    for n, v in regs.items():
        if n in ("R4", "R8", "R12"):
            continue  # the arguments
        assert before.get(n) == v & 0xFFFFFFFF, (n, before.get(n), v)  # the seeds took
    changed = {
        n: (before[n], after[n])
        for n in before
        if n not in SCRATCH | FLAGS | RUNNING and before[n] != after[n]
    }
    assert not changed, changed
    assert ker.depth_after == (
        ker.depth_before[0],
        ker.depth_before[1],
        ker.depth_before[2] - 1,
    ), (
        ker.depth_before,
        ker.depth_after,
    )
    # the kernel's result from these registers equals the C's (from its default ones), and nothing else was written
    got = (ker.get(OUT, size), ker.get(S, 8))
    for addr, key in ((F, "f"), (Q, "q"), (G, "g"), (IN, "in")):
        assert ker.get(addr, len(c[key]))[2:-2] == c[key]
    want = render(cores[1], c, size)
    assert got == want[:2]


