def test_shipping_kernel_has_no_data_transfer_in_simd_mode() -> None:
    """The module ships resonator_svf4_sm.s, and the encoding gate's SIMD-memory check finds nothing in it (it finds the
    SIMD loads and stores of resonator_svf4.s, which hung the DSP on the unit in H-opt1)."""
    from tools.patchkit import pk_encoding_gate as gate

    toml = (ROOT / "modules" / "machines" / "plaits-48k" / "module.toml").read_text()
    assert "lib/resonator_svf4_sm.s" in toml and "lib/resonator_svf4.s" not in toml

    def transfers(name: str) -> int:
        linked = pk_sharc.link(pk_sharc.assemble((LIB / name).read_text()), BASE_SW, {})

        class Mem:
            def read_sw(self, pc: int, size: int = 6) -> bytes | None:
                lo = 2 * (pc - BASE_SW)
                data = linked.code_boot
                return data[lo : lo + size] if lo + size <= len(data) else None

        end = BASE_SW + len(linked.code_boot) // 2
        return len(gate.check_simd_memory(Mem(), [(BASE_SW, end)]))

    assert transfers("resonator_svf4_sm.s") == 0
    assert transfers("resonator_svf4.s") > 0


@pytest.mark.parametrize("name", ["resonator_svf4_sm.s", "resonator_svf4.s"])
def test_kernels_store_no_dag_register_through_its_own_dag(name: str) -> None:
    """PRM pp.14-12/16-7: a DAG1 register may not be transferred through DAG1 (H-opt1 pushed seven with
    `DM(I7, M7) = M4`...); the kernels push them through R0."""
    from tools.patchkit import pk_encoding_gate as gate

    linked = pk_sharc.link(pk_sharc.assemble((LIB / name).read_text()), BASE_SW, {})

    class Mem:
        def read_sw(self, pc: int, size: int = 6) -> bytes | None:
            lo = 2 * (pc - BASE_SW)
            data = linked.code_boot
            return data[lo : lo + size] if lo + size <= len(data) else None

    end = BASE_SW + len(linked.code_boot) // 2
    assert gate.check_same_dag(Mem(), [(BASE_SW, end)]) == []
